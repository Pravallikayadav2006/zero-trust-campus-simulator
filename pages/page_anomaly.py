"""Page 4 - AI-Based Anomaly Detection: model status, evaluation on the synthetic test set, live scoring."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402
import streamlit as st  # noqa: E402

import config  # noqa: E402
from data.synthetic import FEATURE_DESCRIPTIONS, FEATURES  # noqa: E402
from models.anomaly import METHOD_IF, features_from_context  # noqa: E402
from utils import ui, visualization as viz  # noqa: E402
from utils.validation import normalize_context  # noqa: E402

db, detector = ui.get_runtime()


def retrain() -> None:
    _, det = ui.get_runtime()
    det.seed = int(st.session_state["an_seed"])
    det.fit()


st.title("AI-Based Anomaly Detection")
status = detector.status()

if status["method"] == METHOD_IF:
    st.success("Isolation Forest is trained and active. Transparent rules run alongside it and explain the result.")
else:
    st.warning(status["warning"] or "Using the rule-based fallback.")
st.info("**Read this before quoting numbers.** All data on this page is synthetic and was generated by this project. "
        "Metrics measure how well the model separates *simulated* anomalies from *simulated* normal behaviour. "
        "They say nothing about accuracy on a real network. Flagged activity is 'suspicious simulated activity', "
        "not a confirmed attack.")

tab_eval, tab_try, tab_data = st.tabs(["Model evaluation", "Try the detector", "Datasets and method"])

# ----------------------------------------------------------------------------- evaluation
with tab_eval:
    metrics, rule_metrics = status["metrics"], status["rule_metrics"]
    if metrics is None:
        st.warning("The Isolation Forest could not be trained, so there are no model metrics. "
                   "Rule-based metrics are shown below if the test set could be generated.")
    else:
        a, b, c, d = st.columns(4)
        a.metric("Precision", f"{metrics['precision']:.3f}", help="Of the windows flagged, how many were truly simulated anomalies.")
        b.metric("Recall", f"{metrics['recall']:.3f}", help="Of the simulated anomalies, how many were found.")
        c.metric("F1-score", f"{metrics['f1']:.3f}", help="Harmonic mean of precision and recall.")
        d.metric("Test samples", f"{metrics['n_samples']} ({metrics['n_anomalies']} anomalies)")
        left, right = st.columns(2)
        with left:
            ui.show_fig(viz.confusion_matrix_figure(metrics["confusion_matrix"], "Isolation Forest confusion matrix"),
                        key="an_cm")
        with right:
            ui.show_fig(viz.per_type_recall(metrics["per_type_recall"]), key="an_types")
        if detector.pipeline is not None and detector.test_df is not None:
            scores = detector.score_dataframe(detector.test_df)
            ui.show_fig(viz.score_distribution(scores, detector.test_df["label"].to_numpy()), key="an_scores")
    if rule_metrics:
        st.markdown("**Transparent rule-based detector on the same test set**")
        ui.show_fig(viz.metrics_comparison(metrics, rule_metrics), key="an_compare")
        st.caption("The rules were written by the project author after looking at how the synthetic anomalies are "
                   "built, so their near-perfect score is expected and shows nothing about real data. The Isolation "
                   "Forest never sees the labels or the rules.")
    report = {"disclaimer": "Synthetic data only; not evidence of real-world accuracy.", **status}
    st.download_button("Download evaluation report (JSON)", json.dumps(report, indent=2, default=str),
                       file_name="anomaly_evaluation_report.json", mime="application/json")
    with st.expander("Retrain the model"):
        st.number_input("Random seed", 0, 10_000, config.RANDOM_SEED, key="an_seed")
        st.button("Retrain with this seed", on_click=retrain,
                  help="Regenerates both synthetic datasets from the seed and retrains. Same seed = same result.")

# ----------------------------------------------------------------------------- try it
with tab_try:
    st.markdown("Describe one user's behaviour in a 10-minute window and see how it is scored.")
    with st.form("an_try"):
        r1, r2, r3 = st.columns(3)
        rpw = r1.number_input("Requests in the window", 0, 500, 3)
        failed = r1.number_input("Failed authentications", 0, 50, 0)
        freq = r2.number_input("Usual accesses per hour", 0.0, 1000.0, 18.0)
        distinct = r2.number_input("Distinct resources", 0, 50, 1)
        ratio = r3.slider("Failed-request ratio", 0.0, 1.0, 0.0, 0.05)
        hour = r3.slider("Hour of day", 0, 23, 11)
        compliant = st.checkbox("Device is compliant", True)
        go_btn = st.form_submit_button("Score this behaviour", type="primary")
    if go_btn:
        try:
            ctx = normalize_context({"hour": hour, "failed_auth_count": failed, "requests_per_window": rpw,
                                     "access_frequency": freq, "distinct_resources": distinct,
                                     "failed_request_ratio": ratio}, hour)
            result = detector.analyze(features_from_context(ctx, compliant))
        except ValueError as exc:
            st.error(f"Invalid input: {exc}")
        else:
            (st.warning if result.detected else st.success)(result.label + f" - {result.method.replace('_', ' ')}")
            st.progress(min(max(result.score / 100.0, 0.0), 1.0), text=f"Anomaly indicator {result.score:g} / 100")
            if result.imputed:
                st.caption("Missing values replaced by training medians: " + ", ".join(result.imputed))
            st.markdown("**Why? Transparent rules that fired** (the Isolation Forest itself gives no reliable "
                        "per-feature explanation)")
            if result.reasons:
                ui.show_df(pd.DataFrame(result.reasons)[["feature", "value", "points", "rule"]])
            else:
                st.caption("No transparent rule fired.")
            st.caption("Normal-looking behaviour never grants access: the policy engine still decides first.")

# ----------------------------------------------------------------------------- datasets
with tab_data:
    st.markdown(f"""
**Method.** `StandardScaler` -> `IsolationForest` ({status['n_estimators']} trees, fixed seed {status['seed']}) in one
scikit-learn `Pipeline`, so training and inference use identical preprocessing. The model is trained **without labels**.
It is retrained deterministically at start-up instead of loading a pickle file, which avoids unsafe deserialisation.

**Datasets.** Training: {status['train_rows']} synthetic windows (about {detector.train_anomaly_fraction:.0%} anomalies,
seed {status['seed']}). Test: {status['test_rows']} separate windows (about {detector.test_anomaly_fraction:.0%} anomalies,
seed {status['seed'] + 1000}) with known labels. A leakage check aborts training if any feature row appears in both sets.
Missing or infinite values are imputed with training medians; invalid inputs are rejected.
""")
    ui.show_df(pd.DataFrame({"Feature": FEATURES, "Meaning": [FEATURE_DESCRIPTIONS[f] for f in FEATURES]}))
    if detector.train_df is not None and detector.test_df is not None:
        split = st.radio("Preview dataset", ["Training set", "Test set"], horizontal=True)
        frame = detector.train_df if split == "Training set" else detector.test_df
        ui.show_df(frame.head(100))
        st.download_button(f"Download {split.lower()} (CSV)", frame.to_csv(index=False),
                           file_name=f"synthetic_{'train' if split == 'Training set' else 'test'}.csv",
                           mime="text/csv")
        st.caption("Every row is synthetic (is_simulated = 1). Anomaly types: burst, brute force, odd hours, "
                   "resource sweep, noncompliant probe.")
