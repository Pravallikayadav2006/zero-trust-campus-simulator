"""Synthetic behaviour data for the anomaly detector.

Every row is generated by this module with a fixed seed. Nothing is collected
from a real network. Distributions are chosen by the project author to look
plausible; they are NOT calibrated against real traffic.

Features (one row = one user's behaviour in one 10-minute window):

requests_per_window          Requests made in the current window.
failed_auth_count            Failed authentication attempts in the window.
access_frequency             Average accesses per hour over the last 24 hours.
unusual_time                 1 if the request is outside 06:00-22:00, else 0.
distinct_resources           Number of different resources touched in the window.
device_compliant             1 if the device is compliant, else 0.
failed_request_ratio         Share of requests in the window that failed (0-1).
request_frequency_deviation  (requests_per_window - expected) / max(expected, 1),
                             where expected = access_frequency / 6.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

import config

FEATURES = [
    "requests_per_window",
    "failed_auth_count",
    "access_frequency",
    "unusual_time",
    "distinct_resources",
    "device_compliant",
    "failed_request_ratio",
    "request_frequency_deviation",
]

FEATURE_DESCRIPTIONS = {
    "requests_per_window": "Requests in the current 10-minute window",
    "failed_auth_count": "Failed authentication attempts in the window",
    "access_frequency": "Average accesses per hour over the last 24 hours",
    "unusual_time": "1 if the access time is outside 06:00-22:00",
    "distinct_resources": "Distinct resources requested in the window",
    "device_compliant": "1 if the device is compliant",
    "failed_request_ratio": "Failed requests divided by all requests (0-1)",
    "request_frequency_deviation": "Window requests vs. the user's expected rate",
}

ANOMALY_KINDS = ("burst", "brute_force", "odd_hours", "resource_sweep", "noncompliant_probe")


def frequency_deviation(requests_per_window: float, access_frequency: float) -> float:
    expected = access_frequency / config.WINDOWS_PER_HOUR
    return float((requests_per_window - expected) / max(expected, 1.0))


def sample_normal(rng: np.random.Generator) -> dict:
    freq = float(np.clip(rng.lognormal(np.log(18.0), 0.4), 3.0, 90.0))
    rpw = int(min(rng.poisson(3), 12))
    return {
        "requests_per_window": rpw,
        "failed_auth_count": int(min(rng.poisson(0.15), 3)),
        "access_frequency": freq,
        "unusual_time": int(rng.random() < 0.05),
        "distinct_resources": int(min(1 + rng.poisson(0.8), 4)),
        "device_compliant": int(rng.random() < 0.95),
        "failed_request_ratio": float(rng.beta(1, 20)),
    }


def sample_anomaly(rng: np.random.Generator, kind: str) -> dict:
    row = sample_normal(rng)
    if kind == "burst":
        row["requests_per_window"] = int(rng.integers(25, 91))
        row["failed_request_ratio"] = float(rng.beta(2, 10))
        row["distinct_resources"] = int(rng.integers(2, 6))
    elif kind == "brute_force":
        row["failed_auth_count"] = int(rng.integers(4, 13))
        row["failed_request_ratio"] = float(rng.uniform(0.35, 0.95))
        row["requests_per_window"] = int(rng.integers(4, 16))
    elif kind == "odd_hours":
        row["unusual_time"] = 1
        row["requests_per_window"] = int(rng.integers(8, 21))
        row["distinct_resources"] = int(rng.integers(3, 7))
        row["failed_auth_count"] = int(rng.integers(0, 3))
    elif kind == "resource_sweep":
        row["distinct_resources"] = int(rng.integers(6, 13))
        row["requests_per_window"] = int(rng.integers(6, 21))
        row["failed_request_ratio"] = float(rng.uniform(0.05, 0.3))
    elif kind == "noncompliant_probe":
        row["device_compliant"] = 0
        row["failed_auth_count"] = int(rng.integers(2, 6))
        row["distinct_resources"] = int(rng.integers(3, 7))
        row["failed_request_ratio"] = float(rng.uniform(0.2, 0.5))
    else:
        raise ValueError(f"Unknown anomaly kind '{kind}'.")
    return row


def generate_behavior_dataset(n_samples: int, anomaly_fraction: float, seed: int) -> pd.DataFrame:
    """Build a labelled synthetic dataset.

    label = 1 marks a simulated anomaly, 0 a simulated normal window. The label is
    used only for evaluation; the Isolation Forest is trained without it.
    """
    if n_samples <= 0:
        raise ValueError("n_samples must be positive.")
    if not 0.0 <= anomaly_fraction < 1.0:
        raise ValueError("anomaly_fraction must be in [0, 1).")
    rng = np.random.default_rng(seed)
    n_anom = int(round(n_samples * anomaly_fraction))
    rows: list[dict] = []
    kinds: list[str] = []
    for _ in range(n_samples - n_anom):
        rows.append(sample_normal(rng))
        kinds.append("normal")
    for i in range(n_anom):
        kind = ANOMALY_KINDS[i % len(ANOMALY_KINDS)]
        rows.append(sample_anomaly(rng, kind))
        kinds.append(kind)
    df = pd.DataFrame(rows)
    df["request_frequency_deviation"] = [
        frequency_deviation(r, f) for r, f in zip(df["requests_per_window"], df["access_frequency"])
    ]
    df["label"] = [0 if k == "normal" else 1 for k in kinds]
    df["anomaly_type"] = kinds
    df["is_simulated"] = 1
    order = rng.permutation(len(df))
    df = df.iloc[order].reset_index(drop=True)
    return df[FEATURES + ["label", "anomaly_type", "is_simulated"]]
